$r = Invoke-KcPost "$KC/admin/realms/Github/users" @{
    username = 'harold'; enabled = $true; email = 'maximusredor@gmail.com'; emailVerified = $true
    firstName = 'Harold'; lastName = 'Sanchez'
    credentials = @(@{ type = 'password'; value = $testPass; temporary = $false })
}
if ($r -eq 'creado') {
    Add-Content -Path 'c:\Users\harold\OneDrive\Escritorio\proyecto IA devops\Github-Cdk\.env.keycloak-notes' `
        -Value "Usuario de prueba Keycloak -> realm: Github | usuario: harold | password: $testPass" -Encoding ASCII
