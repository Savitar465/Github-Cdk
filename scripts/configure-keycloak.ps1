# Configura Keycloak: realm Github, clientes ms-users y admin-client-java, usuario de prueba.
# Lee los secretos del .env del CDK; no imprime ningun secreto.
$ErrorActionPreference = 'Stop'

$KC = 'http://Github-Keycl-Zsxubd8lEksg-1780593735.us-east-1.elb.amazonaws.com'
$envFile = 'c:\Users\harold\OneDrive\Escritorio\proyecto IA devops\Github-Cdk\.env'

# ?????? Leer .env ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
$envVars = @{}
Get-Content $envFile | ForEach-Object {
    if ($_ -match '^\s*([A-Za-z0-9_]+)\s*=\s*(.*)\s*$') { $envVars[$Matches[1]] = $Matches[2] }
}
$adminPass         = $envVars['KEYCLOAK_ADMIN_PASSWORD']
$msUsersSecret     = $envVars['KEYCLOAK_CLIENT_SECRET']
$adminClientSecret = $envVars['KEYCLOAK_ADMIN_CLIENT_SECRET']
if (-not $adminPass -or -not $msUsersSecret -or -not $adminClientSecret) { throw 'Faltan variables en el .env' }

# ?????? Token de administrador ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
$tokenResp = Invoke-RestMethod -Method Post -Uri "$KC/realms/master/protocol/openid-connect/token" `
    -ContentType 'application/x-www-form-urlencoded' `
    -Body @{ grant_type = 'password'; client_id = 'admin-cli'; username = 'admin'; password = $adminPass }
$headers = @{ Authorization = "Bearer $($tokenResp.access_token)" }
Write-Output 'PASO 1 OK: token de admin obtenido'

function Invoke-KcPost($uri, $bodyObj) {
    $json = $bodyObj | ConvertTo-Json -Depth 10
    try {
        Invoke-RestMethod -Method Post -Uri $uri -Headers $headers -ContentType 'application/json' -Body $json | Out-Null
        return 'creado'
    } catch {
        if ($_.Exception.Response -and [int]$_.Exception.Response.StatusCode -eq 409) { return 'ya existia' }
        throw
    }
}

# ?????? Realm ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
$r = Invoke-KcPost "$KC/admin/realms" @{ realm = 'Github'; enabled = $true; sslRequired = 'none' }
Write-Output "PASO 2 OK: realm Github ($r)"

# Vida del access token: 8 horas. El frontend no renueva tokens y el valor por
# defecto de Keycloak (5 min) corta la sesion a los 5 minutos.
# Ajuste de DEMO: en produccion lo correcto seria implementar refresh tokens.
Invoke-RestMethod -Method Put -Uri "$KC/admin/realms/Github" -Headers $headers `
    -ContentType 'application/json' -Body (@{ accessTokenLifespan = 28800 } | ConvertTo-Json) | Out-Null
Write-Output 'PASO 2b OK: access token lifespan = 8h'

# ?????? Cliente ms-users ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
$r = Invoke-KcPost "$KC/admin/realms/Github/clients" @{
    clientId = 'ms-users'; enabled = $true; protocol = 'openid-connect'
    publicClient = $false; secret = $msUsersSecret
    serviceAccountsEnabled = $true; directAccessGrantsEnabled = $true; standardFlowEnabled = $true
    redirectUris = @('*'); webOrigins = @('*')
}
Write-Output "PASO 3 OK: cliente ms-users ($r)"

# ?????? Cliente admin-client-java ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
$r = Invoke-KcPost "$KC/admin/realms/Github/clients" @{
    clientId = 'admin-client-java'; enabled = $true; protocol = 'openid-connect'
    publicClient = $false; secret = $adminClientSecret
    serviceAccountsEnabled = $true; directAccessGrantsEnabled = $false; standardFlowEnabled = $false
}
Write-Output "PASO 4 OK: cliente admin-client-java ($r)"

# ?????? Rol realm-admin para la service account de admin-client-java ???????????????????????????????????????
$acj  = Invoke-RestMethod -Uri "$KC/admin/realms/Github/clients?clientId=admin-client-java" -Headers $headers
$sa   = Invoke-RestMethod -Uri "$KC/admin/realms/Github/clients/$($acj[0].id)/service-account-user" -Headers $headers
$rm   = Invoke-RestMethod -Uri "$KC/admin/realms/Github/clients?clientId=realm-management" -Headers $headers
$role = Invoke-RestMethod -Uri "$KC/admin/realms/Github/clients/$($rm[0].id)/roles/realm-admin" -Headers $headers
$roleJson = ConvertTo-Json @(@{ id = $role.id; name = $role.name }) -Depth 5
Invoke-RestMethod -Method Post -Uri "$KC/admin/realms/Github/users/$($sa.id)/role-mappings/clients/$($rm[0].id)" `
    -Headers $headers -ContentType 'application/json' -Body $roleJson | Out-Null
Write-Output 'PASO 5 OK: rol realm-admin asignado a admin-client-java'

# ?????? Usuario de prueba ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
$chars = ([char[]](48..57)) + ([char[]](65..90)) + ([char[]](97..122))
